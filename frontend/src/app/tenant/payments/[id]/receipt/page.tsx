import type { Metadata } from "next";
import Link from "next/link";
import { ArrowLeft } from "lucide-react";
import { PrintButton } from "@/components/controls";
import { Logo } from "@/components/logo";
import { Card } from "@/components/ui";
import { requireTenant, serverGet } from "@/lib/server-api";
import { formatDate, formatKES, monthLabel } from "@/lib/format";
import { PAY_METHOD_LABEL, UNIT_TYPE_LABEL, type ReceiptData } from "@/lib/types";

export const metadata: Metadata = { title: "Receipt" };

export default async function ReceiptPage({ params }: { params: { id: string } }) {
  await requireTenant();
  // The API scopes this by the session's tenant: a tenant can never load someone else's receipt (404).
  const { payment, unit, tenantName } = await serverGet<ReceiptData>(`/me/payments/${params.id}`);

  const receiptNo = `DH-${payment._id.slice(-8).toUpperCase()}`;
  const rows: [string, string][] = [
    ["Received from", tenantName],
    ["Unit", unit ? `${unit.unitNumber} (${UNIT_TYPE_LABEL[unit.type]})` : "-"],
    ["Rent for", monthLabel(payment.month)],
    ["Payment method", PAY_METHOD_LABEL[payment.method]],
    ...(payment.referenceCode ? ([["Reference", payment.referenceCode]] as [string, string][]) : []),
    ["Date received", formatDate(payment.paidOn)],
    ...(payment.recordedByName ? ([["Recorded by", payment.recordedByName]] as [string, string][]) : []),
  ];

  return (
    <div className="space-y-4">
      <div className="flex items-center justify-between print:hidden">
        <Link href="/tenant/payments" className="inline-flex items-center gap-1.5 text-sm font-medium text-muted-foreground hover:text-foreground">
          <ArrowLeft className="h-4 w-4" />
          Payments
        </Link>
        <PrintButton label="Download PDF" />
      </div>

      <Card className="mx-auto max-w-xl p-6 sm:p-8 print:max-w-none print:border-0 print:shadow-none">
        <div className="flex items-start justify-between gap-4 border-b pb-5">
          <Logo />
          <div className="text-right">
            <p className="text-xs uppercase tracking-wide text-muted-foreground">Receipt</p>
            <p className="font-mono text-sm font-semibold">{receiptNo}</p>
          </div>
        </div>

        <div className="py-6 text-center">
          <p className="text-sm text-muted-foreground">Amount received</p>
          <p className="mt-1 text-4xl font-extrabold tabular-nums">{formatKES(payment.amount)}</p>
        </div>

        <dl className="divide-y border-y text-sm">
          {rows.map(([k, v]) => (
            <div key={k} className="flex justify-between gap-4 py-3">
              <dt className="text-muted-foreground">{k}</dt>
              <dd className="text-right font-medium">{v}</dd>
            </div>
          ))}
        </dl>

        <p className="mt-6 text-center text-xs text-muted-foreground">Thank you for your payment. This receipt was generated by THE DEED HOSTELS.</p>
      </Card>
    </div>
  );
}
